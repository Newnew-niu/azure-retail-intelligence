"""Build serving/catalog.yml from the documentation and the exported database.

    python scripts/build_serving_catalog.py

Sources, in order of preference:
  column list and types   data/serving.duckdb (what actually exists)
  grain                   docs/data_model.md and docs/data_dictionary.md
  column definitions      docs/data_dictionary.md
  KPI definitions         the header comment of sql/mart/01_views.sql
  reporting window        scripts/export_dashboard_data.py
  everything else         serving/catalog_notes.yml (words only, for gaps in the docs)

The build fails if any column has no definition, so the catalog cannot silently degrade.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import duckdb
import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "scripts"))

from export_dashboard_data import FIRST_KEY, LAST_KEY  # noqa: E402

DICTIONARY = PROJECT_ROOT / "docs" / "data_dictionary.md"
DATA_MODEL = PROJECT_ROOT / "docs" / "data_model.md"
MART_SQL = PROJECT_ROOT / "sql" / "mart" / "01_views.sql"
NOTES = PROJECT_ROOT / "serving" / "catalog_notes.yml"
EXPORT = PROJECT_ROOT / "data" / "serving.duckdb"
OUT = PROJECT_ROOT / "serving" / "catalog.yml"
HEADER = "# Generated by scripts/build_serving_catalog.py - do not edit by hand.\n"


def table_rows(text: str) -> list[list[str]]:
    """Cells of every markdown table row in the text."""
    return [[cell.strip() for cell in line.strip().strip("|").split("|")]
            for line in text.splitlines() if line.startswith("|") and not line.startswith("|--")]


def dw_column_definitions(dictionary: str) -> dict[str, dict[str, str]]:
    """{table: {column: description}} from the '### table' sections."""
    definitions: dict[str, dict[str, str]] = {}
    for section in re.split(r"^### ", dictionary, flags=re.M)[1:]:
        table = section.split()[0]
        for cells in table_rows(section):
            if len(cells) == 3 and cells[2] and cells[0] != "Column":
                for column in re.findall(r"`(\w+)`", cells[0]):
                    definitions.setdefault(table, {})[column] = cells[2]
    return definitions


def grains(dictionary: str, data_model: str) -> dict[str, str]:
    """{dataset: grain}; dw from the data model's Grain table, mart from the dictionary."""
    sections = {"dw": data_model.split("## Grain")[1].split("\n## ")[0],
                "mart": dictionary.split("## mart")[1].split("\n## ")[0]}
    found = {}
    for layer, section in sections.items():
        for cells in table_rows(section):
            match = re.fullmatch(r"`(\w+)`", cells[0])
            if match:
                found[f"{layer}.{match[1]}"] = "one row per " + cells[1].replace("`", "").replace("¹", "").strip()
    return found


def kpi_definitions(mart_sql: str) -> dict[str, str]:
    """The 'name  definition' lines of the header comment, split on two or more spaces."""
    block = mart_sql.split("KPI definitions")[1].split("Not calculated")[0]
    pairs = (re.split(r"\s{2,}", line.strip(), maxsplit=1) for line in block.splitlines()[1:] if line.strip())
    return {name: text for name, text in pairs}


def main() -> int:
    notes = yaml.safe_load(NOTES.read_text(encoding="utf-8"))
    dictionary = DICTIONARY.read_text(encoding="utf-8")
    definitions = dw_column_definitions(dictionary)
    grain_of = grains(dictionary, DATA_MODEL.read_text(encoding="utf-8"))
    export = duckdb.connect(str(EXPORT), read_only=True)

    datasets, missing = {}, []
    for name, note in notes["datasets"].items():
        schema, table = name.split(".")
        rows = export.execute("SELECT column_name, data_type FROM information_schema.columns "
                              "WHERE table_schema = ? AND table_name = ? ORDER BY ordinal_position",
                              [schema, table]).fetchall()
        overrides = note.get("columns") or {}
        columns = []
        for column, data_type in rows:
            definition = (overrides.get(column) or definitions.get(table, {}).get(column)
                          or notes["shared_columns"].get(column))
            if not definition:
                missing.append(f"{name}.{column}")
            columns.append({"name": column, "type": data_type, "definition": definition})
        datasets[name] = {"description": " ".join(note["description"].split()),
                          "grain": grain_of[name],
                          "layer": schema,
                          "source": note["source"],
                          "owner": notes["owner"],
                          "columns": columns}
    export.close()
    if missing:
        raise SystemExit(f"{len(missing)} columns have no definition:\n  " + "\n  ".join(missing))

    catalog = {"owner": notes["owner"],
               "sql_dialect": "DuckDB (the azuresql backend translates it to T-SQL)",
               "reporting_window": {"first_purchase_date_key": FIRST_KEY,
                                    "last_purchase_date_key": LAST_KEY,
                                    "note": " ".join(notes["reporting_window_note"].split())},
               "kpi_definitions": kpi_definitions(MART_SQL.read_text(encoding="utf-8")),
               "datasets": datasets}
    OUT.write_text(HEADER + yaml.safe_dump(catalog, sort_keys=False, allow_unicode=True, width=100),
                   encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(PROJECT_ROOT)}: {len(datasets)} datasets, "
          f"{sum(len(d['columns']) for d in datasets.values())} columns")
    return 0


if __name__ == "__main__":
    sys.exit(main())
