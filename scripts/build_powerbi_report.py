"""Generate the three Power BI report pages (PBIR format) from one reviewable layout.

    python scripts/build_powerbi_report.py [--report-dir powerbi/RetailIntelligence.Report]

Replaces definition/pages/ and the report-level filter in definition/report.json; the theme
and other files written by Power BI Desktop are kept. Power BI Desktop must be CLOSED.
Fields refer to the semantic model generated by scripts/build_powerbi_model.py.

Pages (1280 x 720)
  1. Sales Performance            - product sales, orders, AOV, customers; trend, category, state
  2. Delivery and Operations      - delivery time, late rate, review score by delivery outcome
  3. Customer and Product Insights - repeat rate, category table, payment mix, customers by state
Report filter: dim_date[In Reporting Window] = TRUE (Jan 2017 - Aug 2018, complete months).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REPORT_DIR = PROJECT_ROOT / "powerbi" / "RetailIntelligence.Report"
SCHEMA = "https://developer.microsoft.com/json-schemas/fabric/item/report/definition"
PAGE_SCHEMA = f"{SCHEMA}/page/2.1.0/schema.json"
PAGES_SCHEMA = f"{SCHEMA}/pagesMetadata/1.1.0/schema.json"
VISUAL_SCHEMA = f"{SCHEMA}/visualContainer/1.0.0/schema.json"
# Month axes use dim_date[year_month] ('2018-01'), not a date column with a 'mmm yyyy' format:
# month names would follow the viewer's Windows language, the text key reads the same everywhere.
FOOTNOTE = ("Olist Brazilian E-Commerce (public dataset), Jan 2017 - Aug 2018. Amounts in BRL (Brazilian real). "
            "Sales orders exclude canceled and unavailable orders.")

# Measures and the table that hosts them (must match build_powerbi_model.MEASURES)
MEASURE_TABLE = {
    "Product Sales": "fact_order_items", "Freight": "fact_order_items", "Items Sold": "fact_order_items",
    "Avg Item Price": "fact_order_items", "Avg Review Score of Item Orders": "fact_order_items",
    "Payment Value": "fact_payments", "Payment Value Share": "fact_payments", "Avg Installments": "fact_payments",
}


def ident(*parts: str) -> str:
    """Stable 20-character name, like the ones Power BI Desktop generates."""
    return hashlib.sha1("/".join(parts).encode("utf-8")).hexdigest()[:20]


def literal(value: str) -> dict:
    return {"expr": {"Literal": {"Value": value}}}


def measure(name: str) -> dict:
    return {"Measure": {"Expression": {"SourceRef": {"Entity": MEASURE_TABLE.get(name, "fact_orders")}}, "Property": name}}


def column(table: str, name: str) -> dict:
    return {"Column": {"Expression": {"SourceRef": {"Entity": table}}, "Property": name}}


def projection(field: dict) -> dict:
    kind = "Measure" if "Measure" in field else "Column"
    entity = field[kind]["Expression"]["SourceRef"]["Entity"]
    prop = field[kind]["Property"]
    return {"field": field, "queryRef": f"{entity}.{prop}", "nativeQueryRef": prop}


def title(text: str) -> dict:
    return {"title": [{"properties": {"show": literal("true"), "text": literal(f"'{text}'")}}]}


def visual(page: str, key: str, visual_type: str, box: tuple[int, int, int, int], roles: dict[str, list[dict]] | None = None,
           heading: str | None = None, sort: dict | None = None, objects: dict | None = None, z: int = 0,
           ascending: bool = False) -> dict:
    x, y, w, h = box
    body: dict = {"visualType": visual_type, "drillFilterOtherVisuals": True}
    if roles:
        body["query"] = {"queryState": {role: {"projections": [projection(f) for f in fields]}
                                        for role, fields in roles.items()}}
        if sort:
            body["query"]["sortDefinition"] = {"sort": [{"field": sort, "direction": "Ascending" if ascending else "Descending"}],
                                               "isDefaultSort": True}
    if objects:
        body["objects"] = objects
    if heading:
        body["visualContainerObjects"] = title(heading)
    return {"$schema": VISUAL_SCHEMA, "name": ident(page, key),
            "position": {"x": x, "y": y, "z": z, "width": w, "height": h, "tabOrder": z}, "visual": body}


def textbox(page: str, key: str, box: tuple[int, int, int, int], text: str, size: str = "10pt",
            bold: bool = False, z: int = 0) -> dict:
    style = {"fontSize": size}
    if bold:
        style["fontWeight"] = "bold"
    objects = {"general": [{"properties": {"paragraphs": [{"textRuns": [{"value": text, "textStyle": style}]}]}}]}
    return visual(page, key, "textbox", box, objects=objects, z=z)


def header(page: str, heading: str) -> list[dict]:
    return [
        textbox(page, "title", (24, 8, 700, 40), heading, size="20pt", bold=True),
        textbox(page, "footnote", (24, 690, 1232, 26), FOOTNOTE, size="9pt", z=1),
        visual(page, "slicer_date", "slicer", (760, 8, 300, 60), {"Values": [column("dim_date", "date")]},
               objects={"data": [{"properties": {"mode": literal("'Between'")}}]}, z=2),
        visual(page, "slicer_state", "slicer", (1076, 8, 180, 60), {"Values": [column("dim_customer", "state")]},
               objects={"data": [{"properties": {"mode": literal("'Dropdown'")}}]}, z=3),
    ]


def cards(page: str, names: list[str]) -> list[dict]:
    width, gap = 296, 16
    return [visual(page, f"card_{i}", "card", (24 + i * (width + gap), 80, width, 110), {"Values": [measure(n)]}, z=10 + i)
            for i, n in enumerate(names)]


def sales_page() -> tuple[str, list[dict]]:
    p = "Sales Performance"
    return p, header(p, p) + cards(p, ["Product Sales", "Sales Orders", "Average Order Value", "Customers"]) + [
        visual(p, "trend", "lineChart", (24, 206, 760, 250),
               {"Category": [column("dim_date", "year_month")], "Y": [measure("Product Sales")]},
               heading="Product sales by month (BRL, Brazilian real)", sort=column("dim_date", "year_month"), ascending=True, z=20),
        visual(p, "category", "clusteredBarChart", (800, 206, 456, 474),
               {"Category": [column("dim_product", "category_name_en")], "Y": [measure("Product Sales")]},
               heading="Product sales by category (BRL, Brazilian real)", sort=measure("Product Sales"), z=21),
        visual(p, "state", "clusteredColumnChart", (24, 470, 760, 210),
               {"Category": [column("dim_customer", "state")], "Y": [measure("Sales Orders")]},
               heading="Sales orders by customer state", sort=measure("Sales Orders"), z=22),
    ]


def delivery_page() -> tuple[str, list[dict]]:
    p = "Delivery and Operations"
    return p, header(p, p) + cards(p, ["Delivered Orders", "Avg Delivery Days", "Late Delivery Rate", "Avg Review Score"]) + [
        visual(p, "trend", "lineClusteredColumnComboChart", (24, 206, 760, 250),
               {"Category": [column("dim_date", "year_month")], "Y": [measure("Delivered Orders")],
                "Y2": [measure("Late Delivery Rate")]},
               heading="Delivered orders (columns) and late delivery rate (line) by month",
               sort=column("dim_date", "year_month"), ascending=True, z=20),
        visual(p, "state", "clusteredBarChart", (800, 206, 456, 474),
               {"Category": [column("dim_customer", "state")], "Y": [measure("Avg Delivery Days")]},
               heading="Average delivery days by customer state", sort=measure("Avg Delivery Days"), z=21),
        visual(p, "review", "clusteredColumnChart", (24, 470, 500, 210),
               {"Category": [column("fact_orders", "delivery_status")], "Y": [measure("Avg Review Score")]},
               heading="Average review score by delivery outcome", z=22),
        textbox(p, "review_note", (540, 486, 244, 180),
                "Late orders have lower average review scores. This is an association only: the "
                "dashboard does not show that lateness causes the lower score (product, seller and "
                "region are not controlled for).", size="9pt", z=23),
    ]


def customer_page() -> tuple[str, list[dict]]:
    p = "Customer and Product Insights"
    return p, header(p, p) + cards(p, ["Customers", "Repeat Customer Rate", "Items Sold", "Avg Item Price"]) + [
        visual(p, "category_table", "tableEx", (24, 206, 760, 474),
               {"Values": [column("dim_product", "category_name_en"), measure("Items Sold"), measure("Product Sales"),
                           measure("Avg Item Price"), measure("Avg Review Score of Item Orders")]},
               heading="Categories: volume, price and review score of their orders", sort=measure("Product Sales"), z=20),
        visual(p, "payment_mix", "donutChart", (800, 206, 456, 250),
               {"Category": [column("fact_payments", "payment_type")], "Y": [measure("Payment Value")]},
               heading="Payment value by payment type", z=21),
        visual(p, "customers_state", "clusteredBarChart", (800, 470, 456, 210),
               {"Category": [column("dim_customer", "state")], "Y": [measure("Customers")]},
               heading="Customers by state", sort=measure("Customers"), z=22),
    ]


def reporting_window_filter() -> dict:
    target = {"Column": {"Expression": {"SourceRef": {"Source": "d"}}, "Property": "In Reporting Window"}}
    return {"filters": [{
        "name": ident("filter", "reporting_window"),
        "field": column("dim_date", "In Reporting Window"),
        "type": "Categorical",
        "filter": {"Version": 2, "From": [{"Name": "d", "Entity": "dim_date", "Type": 0}],
                   "Where": [{"Condition": {"In": {"Expressions": [target], "Values": [[{"Literal": {"Value": "true"}}]]}}}]},
        "howCreated": "User",
    }]}


def build(report_dir: Path) -> None:
    definition = report_dir / "definition"
    pages_dir = definition / "pages"
    if pages_dir.exists():
        shutil.rmtree(pages_dir)
    pages_dir.mkdir(parents=True)

    order = []
    for page_name, visuals in [sales_page(), delivery_page(), customer_page()]:
        page_id = ident("page", page_name)
        order.append(page_id)
        page_dir = pages_dir / page_id
        (page_dir / "visuals").mkdir(parents=True)
        write_json(page_dir / "page.json", {"$schema": PAGE_SCHEMA, "name": page_id, "displayName": page_name,
                                            "displayOption": "FitToPage", "height": 720, "width": 1280})
        for v in visuals:
            write_json(page_dir / "visuals" / v["name"] / "visual.json", v)
    write_json(pages_dir / "pages.json", {"$schema": PAGES_SCHEMA, "pageOrder": order, "activePageName": order[0]})

    report = json.loads((definition / "report.json").read_text(encoding="utf-8"))
    report["filterConfig"] = reporting_window_filter()
    write_json(definition / "report.json", report)
    print(f"Wrote {len(order)} pages to {pages_dir}")


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--report-dir", type=Path, default=DEFAULT_REPORT_DIR)
    args = parser.parse_args()
    build(args.report_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
