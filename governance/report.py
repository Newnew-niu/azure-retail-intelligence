"""Render the access review as Markdown, with environment-specific names redacted.

Resource names end in a suffix derived from the subscription ID, and the SQL server name is
also its public hostname, so the suffix, the subscription ID and any extra values are replaced
before anything is written. The rendered report is what gets committed as evidence.
"""
from __future__ import annotations

import hashlib
import re

from governance.access import AccessReview, Grant
from governance.residency import Check

STATUS_ICON = {"PASS": "✅ PASS", "WARN": "⚠️ WARN", "FAIL": "❌ FAIL"}


def resource_suffix(subscription_id: str) -> str:
    """The suffix infra/provision.sh appends to globally unique names."""
    return hashlib.md5(subscription_id.encode()).hexdigest()[:6]


def redact(text: str, subscription_id: str, extra: list[str] = ()) -> str:
    secrets = sorted({s for s in [subscription_id, *extra] if s}, key=len, reverse=True)
    for secret in secrets:
        text = re.sub(re.escape(secret), "<redacted>", text, flags=re.I)
    if subscription_id:
        text = re.sub(re.escape(resource_suffix(subscription_id)), "xxxxxx", text, flags=re.I)
    return text


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _grant_list(grants: set[Grant]) -> str:
    return "<br>".join(g.describe() for g in sorted(grants)) or "–"


def access_section(review: AccessReview) -> tuple[Check, str]:
    rows = []
    for r in review.identities:
        if not r.user_name:
            state = f"not configured (`{r.identity.env_var}` unset)"
        else:
            state = "exists" if r.exists else "**does not exist**"
        rows.append([r.identity.label, f"`{r.user_name or '–'}`", state, str(len(r.approved)),
                     str(len(r.actual)), _grant_list(r.unexpected), _grant_list(r.missing),
                     STATUS_ICON[r.status] + (f" {r.identity.note}" if r.status == "WARN" else "")])
    parts = [_table(["Identity", "Database user", "State", "Approved grants", "Actual grants",
                     "Unexpected", "Missing", "Result"], rows)]
    unknown = [[f"`{p}`", _grant_list(g)] for p, g in sorted(review.unknown_principals.items())]
    parts.append("**Principals not in the approved list:** " + ("none." if not unknown else ""))
    if unknown:
        parts.append(_table(["Principal", "Grants"], unknown))
    parts.append("**Fixed or custom role memberships:** " + (
        ", ".join(f"`{m}` in `{r}`" for r, m in sorted(review.role_members)) or "none."))
    parts.append("**Grants to `public` beyond the SQL Server defaults:** " + (_grant_list(review.public_grants)
                                                                             if review.public_grants else "none."))
    parts.append("**DENY entries:** " + (_grant_list(review.denies) if review.denies else "none."))
    detail = {"PASS": "Every database principal holds exactly its approved grants.",
              "WARN": "Approved grants match; an identity that is not required yet does not exist.",
              "FAIL": "At least one principal holds unapproved access, or approved access is missing."}
    return Check("Database grants = approved scripts", review.status, detail[review.status]), "\n\n".join(parts)


def render(run_date: str, scope: str, checks: list[Check], access: tuple[Check, str] | None,
           notes: list[str]) -> str:
    all_checks = checks + ([access[0]] if access else [])
    overall = ("FAIL" if any(c.status == "FAIL" for c in all_checks)
               else "WARN" if any(c.status == "WARN" for c in all_checks) else "PASS")
    out = [f"# Access and residency review – {run_date}", "",
           f"Generated by `scripts/access_review.py`. Scope: {scope}. Controls C11, C17 and gap G6 in "
           "[GOVERNANCE.md](../GOVERNANCE.md). Environment-specific names are redacted.", "",
           f"**Overall result: {STATUS_ICON[overall]}**", "",
           _table(["Check", "Result", "Detail"], [[c.name, STATUS_ICON[c.status], c.detail] for c in all_checks])]
    for check in checks:
        out += ["", f"## {check.name}", ""]
        if check.rows:
            header = {"Resources in approved EU regions": ["Name", "Type", "Region", "Approved"],
                      "Allowed-locations policy": ["Assignment", "Applies to", "Owner", "Enforced",
                                                   "Allowed regions", "Not approved"],
                      "Encryption at rest": ["Resource", "Setting", "State"],
                      "Azure SQL auditing": ["Server", "State"]}.get(check.name, [])
            out.append(_table(header, check.rows))
        else:
            out.append(check.detail)
    if access:
        out += ["", f"## {access[0].name}", "", access[1]]
    if notes:
        out += ["", "## Notes", ""] + [f"- {n}" for n in notes]
    out += ["", "## Reviewer sign-off", "",
            "| Reviewer | Date | Decision (accept / remediate) | Actions |", "|---|---|---|---|", "| | | | |", ""]
    return "\n".join(out)
